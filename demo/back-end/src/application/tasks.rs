//! Outbox task payloads (the wire DTOs) and their constructors. Names are `[A-Za-z0-9_]` only
//! (decision D-05): the library's diagnostics print other names as `unknown`.
//!
//! Tasks are built by the application layer *before* the command runs and are handed to the
//! executor; the repository writes event + tasks in one SQL statement. A rejected command writes
//! nothing, so a task is never published without its event.
use crate::{
    application::command_service::CommandMetadata,
    domain::{
        ConcertId, FanId,
        shared::venue::{SeatId, Zone},
    },
};
use cqrsx::task::{NewTask, TaskValidationError, format::TaskPayload};
use serde::{Deserialize, Serialize};
use serde_json::json;
use uuid::Uuid;

/// `Concert::SeatBooked` → `Fan.RecordTicket`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RecordTicketV1 {
    pub booking_id: Uuid,
    pub concert_id: ConcertId,
    pub seat: SeatId,
    pub zone: Zone,
    pub price: u32,
    pub fan_id: FanId,
    pub fan_name: String,
}

impl TaskPayload for RecordTicketV1 {
    const TASK_TYPE: &'static str = "encore_record_ticket";
    const TASK_VERSION: i32 = 1;
}

